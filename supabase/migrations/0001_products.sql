create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  "sourceLanguage" text not null default 'it' check ("sourceLanguage" in ('it', 'en', 'es')),
  "nameIt" text not null,
  "descriptionIt" text not null,
  "nameEn" text,
  "descriptionEn" text,
  "nameEs" text,
  "descriptionEs" text,
  "priceCents" integer not null default 0,
  currency varchar(3) not null default 'EUR',
  "imageUrl" text,
  "whatsappMessage" text,
  "isPublished" integer not null default 1,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create index if not exists products_published_created_idx
  on public.products ("isPublished", "createdAt" desc);

create or replace function public.set_products_updated_at()
returns trigger
language plpgsql
as $$
begin
  new."updatedAt" = now();
  return new;
end;
$$;

drop trigger if exists products_updated_at on public.products;
create trigger products_updated_at
before update on public.products
for each row execute function public.set_products_updated_at();

-- The application accesses this table only through the server-side secret key.
alter table public.products disable row level security;
