-- Additive public-site settings and artisan submission workflow. No existing rows are changed.
create table if not exists public.site_settings (
  id smallint primary key default 1 check (id = 1),
  "facebookUrl" text,
  "instagramUrl" text,
  "updatedAt" timestamptz not null default now()
);
insert into public.site_settings (id) values (1) on conflict (id) do nothing;
alter table public.site_settings enable row level security;
revoke all on table public.site_settings from anon, authenticated;
grant select (id, "facebookUrl", "instagramUrl", "updatedAt") on public.site_settings to anon, authenticated;
grant all on public.site_settings to service_role;
drop policy if exists "Public can read site settings" on public.site_settings;
create policy "Public can read site settings" on public.site_settings
  for select to anon, authenticated using (id = 1);

create table if not exists public.artisan_submissions (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  "artisanName" text not null,
  "contactEmail" text not null,
  "contactPhone" text,
  "productName" text not null,
  description text not null,
  category text not null,
  "priceCents" integer not null check ("priceCents" between 0 and 100000000),
  currency varchar(3) not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'changes_requested')),
  "imagePath" text not null,
  "imageUrl" text,
  "correctionNote" text,
  "moderationNote" text,
  "approvedAt" timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  check ((status = 'approved' and "imageUrl" is not null and "approvedAt" is not null) or status <> 'approved')
);
create index if not exists artisan_submissions_status_created_idx on public.artisan_submissions (status, "createdAt" desc);
alter table public.artisan_submissions enable row level security;
revoke all on table public.artisan_submissions from anon, authenticated;
grant select (id, slug, "artisanName", "productName", description, category, "priceCents", currency, status, "imageUrl", "createdAt", "approvedAt", "updatedAt") on public.artisan_submissions to anon, authenticated;
grant all on public.artisan_submissions to service_role;
grant usage, select on sequence public.artisan_submissions_id_seq to service_role;
drop policy if exists "Public can read approved artisan submissions" on public.artisan_submissions;
create policy "Public can read approved artisan submissions" on public.artisan_submissions
  for select to anon, authenticated using (status = 'approved');

