-- Stores only keyed fingerprints and rolling-window timestamps, never source IP addresses.
create table if not exists public.artisan_submission_rate_limits (
  fingerprint text not null,
  submitted_at timestamptz not null default now()
);
alter table public.artisan_submission_rate_limits enable row level security;
revoke all on table public.artisan_submission_rate_limits from anon, authenticated;
grant all on public.artisan_submission_rate_limits to service_role;
create index if not exists artisan_submission_rate_limits_recent_idx on public.artisan_submission_rate_limits (fingerprint, submitted_at desc);
create or replace function public.consume_artisan_submission_quota(p_fingerprint text)
returns boolean language plpgsql security definer set search_path = public as $$
declare recent_count integer;
begin
  if p_fingerprint is null or length(p_fingerprint) <> 64 then return false; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_fingerprint, 0));
  delete from public.artisan_submission_rate_limits where submitted_at < now() - interval '24 hours';
  select count(*) into recent_count from public.artisan_submission_rate_limits
    where fingerprint = p_fingerprint and submitted_at >= now() - interval '24 hours';
  if recent_count >= 3 then return false; end if;
  insert into public.artisan_submission_rate_limits (fingerprint) values (p_fingerprint);
  return true;
end;
$$;
revoke all on function public.consume_artisan_submission_quota(text) from public, anon, authenticated;
grant execute on function public.consume_artisan_submission_quota(text) to service_role;
